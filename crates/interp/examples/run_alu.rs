use interp::{Vm, FRAME_PTR};

fn main() {
    let code: &[u8] = &[
        0xb7, 0x01, 0x00, 0x00, 0x05, 0x00, 0x00, 0x00, // r1  = 5
        0xb7, 0x02, 0x00, 0x00, 0x07, 0x00, 0x00, 0x00, // r2  = 7
        0x0f, 0x21, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, // r1 += r2
        0x27, 0x01, 0x00, 0x00, 0x03, 0x00, 0x00, 0x00, // r1 *= 3
        0xbf, 0x10, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, // r0  = r1
        0x95, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, // exit
    ];

    let prog = isa::decode(code).expect("decode failed");
    println!("program has {} instructions", prog.len());

    let mut vm = Vm::new();
    let r0 = vm.run(&prog).expect("Vm failed to run");

    println!("final register file:");
    for i in 0..=FRAME_PTR {
        println!("  r{i:<2} = 0x{:016x}", vm.reg(i).unwrap());
    }
    println!("program exit value (r0) = {r0}");
}
